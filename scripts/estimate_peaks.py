"""Locate sampled-grid specific-heat maxima for each lattice size and magnetization."""

import argparse
from pathlib import Path

import pandas as pd


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("file", type=Path, help="CSV generated by run_sweep.py")
    parser.add_argument("--out", type=Path, default=Path("outputs/peaks.csv"))
    args = parser.parse_args()
    data = pd.read_csv(args.file)
    records = []
    for (magnetization, length), group in data.groupby(["m0_requested", "L"]):
        means = group.groupby("T")["specific_heat"].mean().sort_index()
        spacing = means.index.to_series().diff().dropna()
        records.append({
            "m0": magnetization,
            "L": length,
            "peak_temperature_on_grid": means.idxmax(),
            "peak_specific_heat": means.max(),
            "min_temperature_grid_spacing": spacing.min() if not spacing.empty else float("nan"),
        })
    result = pd.DataFrame(records)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    result.to_csv(args.out, index=False)
    print(result.to_string(index=False))


if __name__ == "__main__":
    main()
